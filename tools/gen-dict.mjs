#!/usr/bin/env node
/**
 * GRAND VIEW — generates the browser i18n dictionary module.
 *
 * Reads src/config/i18n/<lang>-{core,services,contact}.json and writes
 * src/js/i18n-dict.js as a plain ESM module (no JSON imports) so it can be
 * loaded directly by the browser via <script type="module">.
 *
 * Usage: node tools/gen-dict.mjs   (run before tools/build.mjs)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const dictDir = join(root, 'src', 'config', 'i18n');
const outPath = join(root, 'src', 'js', 'i18n-dict.js');

const LANGS = ['en', 'ar'];
const PARTS = ['core', 'services', 'contact'];

const DICTIONARY = {};
for (const lang of LANGS) {
  DICTIONARY[lang] = {};
  for (const part of PARTS) {
    const file = join(dictDir, `${lang}-${part}.json`);
    const data = JSON.parse(readFileSync(file, 'utf8'));
    Object.assign(DICTIONARY[lang], data);
  }
}

const LANG_META = {
  en: { dir: 'ltr', name: 'English', htmlLang: 'en', ogLocale: 'en_AE' },
  ar: { dir: 'rtl', name: 'العربية', htmlLang: 'ar', ogLocale: 'ar_AE' },
};

const banner = '/* AUTO-GENERATED by tools/gen-dict.mjs — do not edit by hand. */\n';
const body = [
  `export const LANG_META = ${JSON.stringify(LANG_META, null, 2)};`,
  `export const DICTIONARY = ${JSON.stringify(DICTIONARY, null, 2)};`,
  `export function currentLang() {
  if (typeof window === 'undefined') return 'en';
  const q = new URLSearchParams(window.location.search).get('lang');
  if (q === 'ar' || q === 'en') return q;
  const html = document.documentElement.getAttribute('lang');
  return html === 'ar' ? 'ar' : 'en';
}`,
  `export function t(lang, key, vars) {
  const d = DICTIONARY[lang] || DICTIONARY.en;
  let s = d[key];
  if (s == null) s = DICTIONARY.en[key] == null ? '' : DICTIONARY.en[key];
  if (vars && typeof s === 'string') {
    for (const [k, v] of Object.entries(vars)) s = s.split('{{' + k + '}}').join(String(v));
  }
  return s;
}`,
].join('\n\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, banner + body + '\n');

const enKeys = Object.keys(DICTIONARY.en).length;
const arKeys = Object.keys(DICTIONARY.ar).length;
console.log(`Wrote ${outPath} (en=${enKeys} keys, ar=${arKeys} keys)`);
